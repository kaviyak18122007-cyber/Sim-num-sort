# Unsorted list
numbers = [42, 12, 89, 7, 23, 56, 1]

# Ascending order (Chinna number-la irundhu Periya number)
ascending = sorted(numbers)

# Descending order (Periya number-la irundhu Chinna number)
descending = sorted(numbers, reverse=True)

print("Original List  :", numbers)
print("Ascending List :", ascending)
print("Descending List:", descending)
